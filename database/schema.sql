create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id) on delete cascade,
  username varchar(80) not null,
  bio varchar(500) not null default '',
  avatar varchar(20) not null default '🌙',
  avatar_frame text not null default 'sunny' check (avatar_frame in ('sunny','sky','mint','lavender','peach')),
  created_at timestamptz not null default now()
);

alter table public.users add column if not exists auth_user_id uuid references auth.users(id) on delete cascade;
alter table public.users add column if not exists avatar_frame text not null default 'sunny';
create unique index if not exists idx_users_auth_user_id_unique on public.users(auth_user_id);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title varchar(120) not null,
  description text not null default '',
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  target_minutes smallint not null default 25 check (target_minutes between 5 and 600),
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.journals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  task_id bigint references public.tasks(id) on delete set null,
  title varchar(150) not null default 'Focus session',
  duration_minutes smallint not null check (duration_minutes between 1 and 1440),
  reflection text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.soundtracks (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name varchar(100) not null,
  category varchar(60) not null default 'Ambient',
  description varchar(500) not null default '',
  url varchar(1000) not null,
  favorite boolean not null default false,
  created_at timestamptz not null default now(),
  unique(user_id, name)
);

create table if not exists public.focus_sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  task_id bigint references public.tasks(id) on delete set null,
  duration_minutes smallint not null check (duration_minutes between 1 and 1440),
  started_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_tasks_user_created on public.tasks(user_id, created_at desc);
create index if not exists idx_journals_user_created on public.journals(user_id, created_at desc);
create index if not exists idx_focus_user_started on public.focus_sessions(user_id, started_at desc);

-- The API uses a private server-side key. RLS stays enabled to prevent anon-key access.
alter table public.users enable row level security;
alter table public.tasks enable row level security;
alter table public.journals enable row level security;
alter table public.soundtracks enable row level security;
alter table public.focus_sessions enable row level security;

